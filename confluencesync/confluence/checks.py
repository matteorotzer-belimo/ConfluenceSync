"""Storage format checks (adapted from belimo_ticket-analytics scripts/confluence_sync.py).

- the generated page must be valid XHTML/storage format and only use allowed macros
- protected items of an existing page (app macros, images, attachment links, inline comment
  markers) must not get lost silently when the page is overwritten
"""
from __future__ import annotations

import hashlib
import html.entities
import re
import xml.etree.ElementTree as ET
from collections import Counter

NS = {"ac": "http://atlassian.com/content", "ri": "http://atlassian.com/resource/identifier",
      "at": "http://atlassian.com/template"}
ENTITY = re.compile(r"&([A-Za-z][A-Za-z0-9]*);")
XML_ENTITIES = {"amp", "lt", "gt", "quot", "apos"}

ALLOWED_MACROS = {"info", "note", "warning", "tip", "panel", "status", "expand", "toc",
                  "pagetree", "children", "code", "anchor", "excerpt"}
OWN_ATTACHMENT_PREFIX = "cs-"


class StorageError(Exception):
    pass


def norm(text: str) -> str:
    return text.replace("\r\n", "\n")


def content_hash(text: str) -> str:
    """Hash of a page body, insensitive to line endings and whitespace between tags."""
    compact = re.sub(r">\s+<", "><", norm(text).strip())
    return hashlib.sha256(compact.encode("utf-8")).hexdigest()


def q(name: str) -> str:
    """'ac:name' -> '{http://atlassian.com/content}name' (how ElementTree names it)."""
    prefix, _, local = name.partition(":")
    return f"{{{NS[prefix]}}}{local}" if local else name


def parse_storage(text: str) -> ET.Element:
    """Parse storage format (XHTML with ac:/ri: elements). HTML entities like &nbsp; are allowed."""
    def numeric(m: re.Match) -> str:
        name = m.group(1)
        chars = html.entities.html5.get(name + ";")
        if name in XML_ENTITIES or chars is None:
            return m.group(0)
        return "".join(f"&#{ord(c)};" for c in chars)

    ns = " ".join(f'xmlns:{k}="{v}"' for k, v in NS.items())
    try:
        return ET.fromstring(f"<storage {ns}>{ENTITY.sub(numeric, text)}</storage>")
    except ET.ParseError as exc:
        raise StorageError(f"kein gültiges Storage-Format: {exc}") from None


def _canon(el: ET.Element) -> tuple:
    return (el.tag, tuple(sorted(el.attrib.items())), el.text or "",
            tuple(_canon(child) + (child.tail or "",) for child in el))


def protected_items(root: ET.Element, allowed_macros: set[str] = ALLOWED_MACROS) -> Counter:
    """App macros, foreign images/attachments and inline comment markers of a page.

    Images and attachments that ConfluenceSync uploaded itself (prefix 'cs-') are not protected:
    they are part of the managed content.
    """
    parents = {child: parent for parent in root.iter() for child in parent}
    items: Counter = Counter()
    for el in root.iter():
        if el.tag == q("ac:structured-macro"):
            name = el.get(q("ac:name"), "")
            if name not in allowed_macros:
                items[("macro", name, _canon(el))] += 1
        elif el.tag == q("ac:image"):
            source = next((c.get(q("ri:filename")) or c.get(q("ri:value")) for c in el), None) or "?"
            if not source.startswith(OWN_ATTACHMENT_PREFIX):
                items[("image", source, _canon(el))] += 1
        elif el.tag == q("ri:attachment"):
            holder = parents.get(el)
            if holder is not None and holder.tag == q("ac:image"):
                continue
            filename = el.get(q("ri:filename"), "?")
            holder = holder if holder is not None and holder.tag == q("ac:link") else el
            if not filename.startswith(OWN_ATTACHMENT_PREFIX):
                items[("attachment", filename, _canon(holder))] += 1
        elif el.tag == q("ac:inline-comment-marker"):
            items[("comment", el.get(q("ac:ref"), "?"), "".join(el.itertext()))] += 1
    return items


LOST = {
    "macro": "App-Makro «{}»",
    "image": "Bild «{}» (von Hand eingefügt)",
    "attachment": "Link auf Anhang «{}»",
    "comment": "Inline-Kommentar",
}


def lost_items(current: str, new: str) -> list[str]:
    """Protected items of the current Confluence page that the new body would remove."""
    try:
        before = protected_items(parse_storage(current))
    except StorageError:
        return []
    after = protected_items(parse_storage(new))
    return list(dict.fromkeys(LOST[kind].format(name) for kind, name, _ in (before - after)))


def check_generated(text: str) -> list[str]:
    """Problems of a body generated by ConfluenceSync (should never happen; blocks the upload)."""
    if not text.strip():
        return ["Die Seite ist leer."]
    try:
        root = parse_storage(text)
    except StorageError as exc:
        return [str(exc)]
    problems = []
    for el in root.iter(q("ac:structured-macro")):
        name = el.get(q("ac:name"), "")
        if name not in ALLOWED_MACROS:
            problems.append(f"Makro «{name}» ist nicht erlaubt.")
    for el in root.iter(q("ac:inline-comment-marker")):
        problems.append("Inline-Kommentare können nur in Confluence erstellt werden.")
    return list(dict.fromkeys(problems))
